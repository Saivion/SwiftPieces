const s = (p: Props, k: string) => String(p[k] ?? "");
const n = (p: Props, k: string) => Number(p[k] ?? 0);
const I = (d: number) => INDENT.repeat(d);

/** Camera modes (e.g. Leaf, Whole plant, Flower) and each one's hint: "Title | text" or just the text. */
export function cameraModes(p: Props): { modes: string[]; hints: Array<{ title: string; text: string }>; start: number } {
  const modes = list(p.modes, 5);
  const raw = String(p.modeHints ?? "").split(";").map((x) => x.trim());
  const hints = modes.map((m, i) => {
    const [a = "", b] = (raw[i] ?? "").split("|").map((x) => x.trim());
    return b === undefined ? { title: m, text: a } : { title: a || m, text: b };
  });
  return { modes, hints, start: Math.max(0, Math.min(modes.length - 1, Math.round(Number(p.mode ?? 0)) || 0)) };
}

/** The levels a meter steps through, and which one it starts on (the readout, if it is one). */
export function meterLevels(p: Props): { levels: string[]; start: number } {
  const readout = s(p, "readout").trim();
  const levels = list(p.levels, 8);
  if (!readout) return { levels: [], start: 0 };
  const at = levels.indexOf(readout);
  if (at >= 0) return { levels, start: at };
  return { levels: [readout, ...levels], start: 0 };
}

