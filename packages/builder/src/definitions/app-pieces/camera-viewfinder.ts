// Camera Viewfinder: a full-screen camera view with framing corners, a hint card and either a
// shutter or a continue button. With a readout it becomes a meter: drag across the view (pointing
// the camera) and the big reading steps through its levels with a tick each, optionally over a
// scale of every level with the current one in signal red. The hint card sits at the top or bottom;
// with modes, a strip along the shutter bar switches between them and each brings its own hint.
