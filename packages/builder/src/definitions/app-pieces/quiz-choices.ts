export const quizChoices: SwiftPieceDefinition = {
  id: "quiz-choices",
  name: "Quiz Choices",
  category: "pieces",
  description: "A prompt on a card and the answers it could be. The right pick fills sage with a success tap, a wrong one shakes red, and a panel rises with the answer in a sentence and a button to move on.",
  availability: "free",
  preview: { component: "quiz-choices", chunk: "app-pieces" },
  icon: "checkmark.circle.fill",
  concepts: ["state", "foreach", "animation"],
  interactions: ["tap", "select", "haptic", "push"],
  anatomy: [
    { part: "Prompt", props: ["prompt"] },
    { part: "Answers", props: ["options", "correct"] },
    { part: "Result", props: ["example", "nextTitle", "link"] },
    { part: "State", props: ["answered"] },
  ],
  properties: [
    text("prompt", "Prompt", "Willing to give more than is needed; generous", { maxLength: 140 }),
    text("options", "Answers", "munificent, taciturn, brusque", { maxLength: 120 }),
    number("correct", "Right answer", 0, 0, 4, 1, { hint: "Which answer is right, from 0." }),
    text("example", "In a sentence", "A munificent neighbour paid for the new benches in the park.", { maxLength: 140 }),
    text("nextTitle", "Button", "Next word", { maxLength: 24 }),
    bool("answered", "Starts answered", false, { group: "state" }),
    link("link", "Button opens", { hint: "Leave empty to try again." }),
  ],
  variants: [
    { id: "words", label: "Words", props: {} },
    { id: "capitals", label: "Capitals", props: { prompt: "The capital of Norway", options: "Bergen, Oslo, Trondheim", correct: 1, example: "Oslo sits at the head of the Oslofjord.", nextTitle: "Next question" } },
    { id: "answered", label: "Answered", props: { answered: true } },
  ],
  states: [{ id: "answered", label: "Answered", props: { answered: true } }],
  swift: {
    imports: [],
    emit(p, ctx) {
      ctx.declare("QuizChoices", STRUCT());
      const { options, correct } = quizOptions(p);
      const action = linkAction(ctx, p.link);
      return {
        lines: construct("QuizChoices", [
          `prompt: ${str(s(p, "prompt"))}`,
          arrayArg("options", options.map(str)),
          `correct: ${num(correct)}`,
          s(p, "example").trim() && `example: ${str(s(p, "example").trim())}`,
          s(p, "nextTitle") !== "Next" && `nextTitle: ${str(s(p, "nextTitle"))}`,
          action && `onNext: ${action}`,
          p.answered === true && `picked: ${num(correct)}`,
        ]),
      };
    },
  },
};
