// Quiz Choices: a definition on a card and the words it could be. Pick one: the right answer fills
// sage with a tick and a success tap, a wrong one shakes red with an error tap, and a panel rises
// with the answer used in a sentence and a button to move on.
import type { Props, SwiftPieceDefinition } from "../../core/schema.js";
import { INDENT, list, num, str } from "../../core/swift.js";
import { bool, link, number, text } from "../shared.js";
import { arrayArg, construct, linkAction } from "./emit-link-action.js";

const s = (p: Props, k: string) => String(p[k] ?? "");
const n = (p: Props, k: string) => Number(p[k] ?? 0);
const I = (d: number) => INDENT.repeat(d);

export function quizOptions(p: Props): { options: string[]; correct: number } {
  const options = list(p.options, 5);
  const opts = options.length ? options : ["Answer"];
  return { options: opts, correct: Math.min(opts.length - 1, Math.max(0, Math.round(n(p, "correct")))) };
}

