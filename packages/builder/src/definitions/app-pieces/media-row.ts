/** The house fills that are one flat colour (a picture stand-in with no gradient). */
export const SOLID_ARTS = new Set(["red", "ember", "blush", "azure", "sky", "butter", "sage", "lilac", "sand", "ink"]);
/** The ink (near-black or white) that reads on an art's fill. */
export const artInk = (id: string) => inkOn((ARTS[id] ?? ARTS.ocean).stops[1]);

const artOptions = withArtwork(opts(...Object.entries(ARTS).map(([id, a]): [string, string] => [id, a.label])));

export const mediaRow: SwiftPieceDefinition = {
  id: "media-row",
  name: "Media Row",
  category: "pieces",
  description: "A list item with its picture: title, meta line and a short description, with a play, reorder or add control and an optional swipe to remove.",
  availability: "free",
  preview: { component: "media-row", chunk: "app-pieces" },
  // It pads itself 8 top and bottom; a list adds 4. In a list it stays clear while it slides.
  list: { bare: { listed: true }, pad: 4 },
  icon: "list.bullet",
  concepts: ["state", "gesture", "spring"],
  anatomy: [
    { part: "Picture", props: ["art", "word", "symbol", "thumbSize", "thumbShape"] },
    { part: "Text", props: ["eyebrow", "title", "titleDesign", "meta", "metaIcon", "detail", "progress"] },
    { part: "Trailing control", props: ["trailing"] },
    { part: "Interaction", props: ["swipe", "link", "trailingLink"] },
  ],
  interactions: ["tap", "swipe", "toggle", "haptic"],
  variants: [
    { id: "recipe", label: "Recipe", props: { art: "butter", word: "", eyebrow: "", title: "Chickpea curry", titleDesign: "serif", meta: "40 min · Mains", metaIcon: "clock", detail: "Quick and filling: chickpeas, cauliflower and kale in a mild coconut sauce.", trailing: "none", thumbSize: 76, swipe: false } },
    { id: "episode", label: "Episode", props: { art: "azure", word: "Night Desk", eyebrow: "12 May", title: "Why cities hum after midnight", titleDesign: "default", meta: "56 min", metaIcon: "none", detail: "", trailing: "drag", thumbSize: 52, swipe: true } },
    { id: "playable", label: "Playable", props: { art: "ember", word: "Long Form", eyebrow: "Friday", title: "A week inside a lighthouse", meta: "47 min", metaIcon: "none", detail: "", trailing: "play", thumbSize: 52 } },
  ],
  states: [
    { id: "played", label: "Part played", props: { progress: 60, meta: "15 min left" } },
    { id: "plain", label: "No picture word", props: { word: "" } },
  ],
  properties: [
    select("art", "Picture", "azure", artOptions, { group: "color" }),
    text("word", "Picture word", "Night Desk", { maxLength: 24, hint: "Set on the picture like cover art. Leave empty for a plain picture." }),
    icon("symbol", "Picture symbol", "none", { hint: "Shown on the picture when it has no word." }),
    number("thumbSize", "Picture size", 64, 36, 110, 2, { group: "layout" }),
    select("thumbShape", "Picture shape", "rounded", opts(["rounded", "Rounded"], ["circle", "Circle"]), { group: "shape" }),
    text("eyebrow", "Eyebrow", "12 May", { maxLength: 40, hint: "Small uppercase line above the title (a date, a show). Leave empty for none." }),
    text("title", "Title", "Why cities hum after midnight", { maxLength: 80 }),
    select("titleDesign", "Title font", "default", opts(["default", "System"], ["serif", "Serif"]), { group: "typography" }),
    text("meta", "Meta line", "56 min", { maxLength: 60 }),
    select("metaIcon", "Meta symbol", "none", opts(...Object.entries(MEDIA_META))),
    text("detail", "Description", "", { maxLength: 160, hint: "Two lines at most. Leave empty for a compact row." }),
    number("progress", "Played", 0, 0, 100, 5, { group: "state", hint: "0 hides the bar." }),
    select("trailing", "Trailing control", "drag", opts(...Object.entries(MEDIA_TRAILING).map(([id, t]): [string, string] => [id, t.label]))),
    bool("swipe", "Swipe to remove", true, { group: "interaction" }),
    link("link", "On tap"),
    link("trailingLink", "Trailing control opens", { hint: "Leave empty to toggle it in place (play and pause, add and added)." }),
  ],
  swift: {
    imports: [],
    emit(p, ctx) {
      ctx.declare("MediaRow", VIEW);
      const picture = swiftArtwork(ctx, s(p, "art"));
      const stops = picture ? [artworkGround(s(p, "art"))] : (ARTS[s(p, "art")] ?? ARTS.ocean).stops;
      const t = MEDIA_TRAILING[s(p, "trailing")] ?? MEDIA_TRAILING.none;
      const meta = s(p, "metaIcon");
      const action = linkAction(ctx, p.link);
      const trailingAction = t.symbol ? linkAction(ctx, p.trailingLink) : null;
      const ink = artInk(s(p, "art"));
      const sym = s(p, "symbol");
      return {
        lines: call("MediaRow", [
          ["title", ctx.str(s(p, "title"))],
          s(p, "eyebrow").trim() && ["eyebrow", ctx.str(s(p, "eyebrow").trim())],
          s(p, "meta").trim() && ["meta", ctx.str(s(p, "meta").trim())],
          meta !== "none" && ["metaSymbol", ctx.str(meta)],
          s(p, "detail").trim() && ["detail", ctx.str(s(p, "detail").trim())],
          ["art", `[${(stops.length === 1 ? [stops[0], stops[0]] : stops).map((c) => swiftHex(c)).join(", ")}]`],
          ink !== "#ffffff" && ["ink", swiftHex(ink)],
          s(p, "word").trim() && ["word", ctx.str(s(p, "word").trim())],
          !s(p, "word").trim() && sym && sym !== "none" && ["symbol", ctx.str(ctx.symbol(sym))],
          picture && ["picture", `AnyView(${picture})`],
          n(p, "thumbSize") !== 64 && ["size", num(n(p, "thumbSize"))],
          s(p, "thumbShape") === "circle" && ["circle", "true"],
          s(p, "titleDesign") === "serif" && ["serif", "true"],
          n(p, "progress") > 0 && ["progress", num(n(p, "progress") / 100)],
          t.symbol && ["trailing", ctx.str(t.symbol)],
          t.on && ["trailingOn", ctx.str(t.on)],
          b(p, "swipe") && ["swipeToRemove", "true"],
          b(p, "swipe") && p.listed === true && ["listed", "true"],
          action && ["action", action],
          trailingAction && ["trailingAction", trailingAction],
        ]),
      };
    },
  },
};
