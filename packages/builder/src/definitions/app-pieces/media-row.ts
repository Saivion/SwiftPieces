  "            Text(title)",
  "                .font(serif ? .system(.body, design: .serif).weight(.medium) : .subheadline.weight(.medium))",
  "                .foregroundStyle(.primary)",
  "                .multilineTextAlignment(.leading)",
  "                .lineLimit(2)",
  "            if !meta.isEmpty {",
  "                HStack(spacing: 4) {",
  "                    if !metaSymbol.isEmpty { Image(systemName: metaSymbol) }",
  "                    Text(meta)",
  "                }",
  "                .font(.caption)",
  "                .foregroundStyle(.secondary)",
  "            }",
  "            if let progress {",
  "                ProgressView(value: shown ? progress : 0)",
  "                    .animation(reduceMotion ? nil : .easeOut(duration: 0.3).delay(0.1), value: shown)",
  "                    .frame(width: 48)",
  "                    .tint(.accentColor)",
  "                    .padding(.top, 2)",
  "            }",
  "            if !detail.isEmpty {",
  "                Text(detail)",
